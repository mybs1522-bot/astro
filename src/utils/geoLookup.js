/**
 * Normalizes input city text and finds matching exact latitude & longitude.
 * Robustly strips prefixes like 'village', 'dist', 'taluk', 'tehsil', 'near', etc.
 * @param {string|object} pobInput
 * @returns {{ name: string, state?: string, country: string, lat: number, lon: number, isFallback?: boolean }}
 */
export function lookupCityCoordinates(pobInput) {
  if (!pobInput) {
    return { name: 'New Delhi', state: 'Delhi', country: 'India', lat: 28.6139, lon: 77.2090, isFallback: true };
  }

  // If already an object with lat and lon
  if (typeof pobInput === 'object') {
    if (typeof pobInput.lat === 'number' && typeof pobInput.lon === 'number' && !isNaN(pobInput.lat)) {
      return {
        name: pobInput.name || 'Custom Location',
        state: pobInput.state || '',
        country: pobInput.country || 'India',
        lat: pobInput.lat,
        lon: pobInput.lon
      };
    }
    pobInput = pobInput.name || pobInput.city || '';
  }

  const rawStr = String(pobInput).trim();
  if (!rawStr || rawStr.toLowerCase() === 'not provided' || rawStr.toLowerCase() === 'india') {
    return { name: 'New Delhi', state: 'Delhi', country: 'India', lat: 28.6139, lon: 77.2090, isFallback: true };
  }

  // 1. Direct whole-string match (lowercase)
  const lowerTrimmed = rawStr.toLowerCase();
  if (CITY_COORDINATES_DATABASE[lowerTrimmed]) {
    return { ...CITY_COORDINATES_DATABASE[lowerTrimmed] };
  }

  // 2. Clean and tokenize
  // Strip postal codes, common prefixes and noise words
  const noiseRegex = /\b(dist|district|distt|taluk|taluka|tal|tehsil|tahsil|village|vill|v\.|near|post|po|state|division)\b[:.\s]*/gi;
  const cleanedStr = lowerTrimmed.replace(noiseRegex, ' ');

  const tokens = cleanedStr
    .replace(/[()[\]{}:,./|_-]/g, ' ')
    .split(/\s+/)
    .map(t => t.trim())
    .filter(t => t.length >= 3);

  // Check each token against database
  for (const token of tokens) {
    if (CITY_COORDINATES_DATABASE[token]) {
      return { ...CITY_COORDINATES_DATABASE[token] };
    }
  }

  // Check 2-word combinations (e.g. "new delhi", "cooch behar", "sri muktsar")
  for (let i = 0; i < tokens.length - 1; i++) {
    const pair = `${tokens[i]} ${tokens[i + 1]}`;
    if (CITY_COORDINATES_DATABASE[pair]) {
      return { ...CITY_COORDINATES_DATABASE[pair] };
    }
  }

  // 3. Substring match across known cities (longest match first)
  const sortedKeys = Object.keys(CITY_COORDINATES_DATABASE).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    if (key.length >= 4 && lowerTrimmed.includes(key)) {
      return { ...CITY_COORDINATES_DATABASE[key] };
    }
  }

  // 4. Fallback: Default to New Delhi coordinates with original name preserved
  return {
    name: rawStr,
    state: '',
    country: 'India',
    lat: 28.6139,
    lon: 77.2090,
    isFallback: true
  };
}
